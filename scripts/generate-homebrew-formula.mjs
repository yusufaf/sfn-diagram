#!/usr/bin/env node
// Renders the Homebrew formula for the standalone CLI binaries from a release's
// SHA256SUMS file. The `homebrew-tap` job in .github/workflows/release-please.yml
// pipes the output into Formula/sfn-diagram.rb in the tap repo.
//
// Usage:
//   node scripts/generate-homebrew-formula.mjs --tag sfn-diagram-v1.6.0 --sums binaries/SHA256SUMS
//
// SHA256SUMS is in `sha256sum` format: "<hex>  <asset-name>" per line, and must
// list the four darwin/linux assets built by scripts/build-binaries.mjs.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parseArgs } from 'node:util';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');

const { values } = parseArgs({
    options: {
        repo: { default: 'yusufaf/sfn-diagram', type: 'string' },
        sums: { type: 'string' },
        tag: { type: 'string' },
    },
    strict: true,
});

if (!values.tag || !values.sums) {
    console.error(
        'usage: generate-homebrew-formula.mjs --tag <release-tag> --sums <SHA256SUMS>',
    );
    process.exit(1);
}

const packageJson = JSON.parse(
    readFileSync(path.join(root, 'package.json'), 'utf8'),
);

const checksums = new Map(
    readFileSync(values.sums, 'utf8')
        .split('\n')
        .filter((line) => line.trim() !== '')
        .map((line) => {
            const [hash, ...rest] = line.trim().split(/\s+/);
            // sha256sum prefixes binary-mode names with '*'.
            return [rest.join(' ').replace(/^\*/, ''), hash];
        }),
);

function asset(name) {
    const hash = checksums.get(name);
    if (!hash) {
        console.error(
            `generate-homebrew-formula: ${name} missing from ${values.sums}`,
        );
        process.exit(1);
    }
    return {
        sha256: hash,
        url: `https://github.com/${values.repo}/releases/download/${values.tag}/${name}`,
    };
}

const darwinArm = asset('sfn-diagram-darwin-arm64');
const darwinIntel = asset('sfn-diagram-darwin-x64');
const linuxArm = asset('sfn-diagram-linux-arm64');
const linuxIntel = asset('sfn-diagram-linux-x64');

// Homebrew stages a bare-file URL under its basename, so the install step
// renames whichever platform asset was fetched to the plain `sfn-diagram` bin.
const formula = `# Generated by scripts/generate-homebrew-formula.mjs in ${values.repo}.
# Do not edit by hand; the release workflow overwrites this file on every release.
class SfnDiagram < Formula
  desc "Generate SVG, Mermaid, and HTML diagrams from AWS Step Functions definitions"
  homepage "${packageJson.homepage}"
  version "${packageJson.version}"
  license "${packageJson.license}"

  on_macos do
    on_arm do
      url "${darwinArm.url}"
      sha256 "${darwinArm.sha256}"
    end
    on_intel do
      url "${darwinIntel.url}"
      sha256 "${darwinIntel.sha256}"
    end
  end

  on_linux do
    on_arm do
      url "${linuxArm.url}"
      sha256 "${linuxArm.sha256}"
    end
    on_intel do
      url "${linuxIntel.url}"
      sha256 "${linuxIntel.sha256}"
    end
  end

  def install
    bin.install Dir["sfn-diagram-*"].first => "sfn-diagram"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sfn-diagram --version")
    (testpath/"simple.asl.json").write <<~EOS
      {"StartAt":"Hello","States":{"Hello":{"Type":"Pass","End":true}}}
    EOS
    assert_match "<svg", shell_output("#{bin}/sfn-diagram #{testpath}/simple.asl.json --format svg")
  end
end
`;

process.stdout.write(formula);
